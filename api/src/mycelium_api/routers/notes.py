@router.post("", response_model=NoteOut)
async def create_note(
    body: NoteCreateIn,
    ctx: Annotated[TenantCtx, Depends(tenant_ctx, scope="function")],
    # Optional, and the same reasoning as the task create: every client
    # today creates without one, and what the header buys is for a caller
    # that cannot tell a create which never arrived from one whose answer
    # was lost. Claimed in the SAME transaction as the create, so a retry
    # replays the first answer instead of writing a second note.
    idempotency_key: Annotated[str | None, Header(alias="Idempotency-Key")] = None,
) -> NoteOut:
    claimed = await idem.claim_optional(
        ctx.session,
        org_id=ctx.org_id,
        actor_id=ctx.user_id,
        endpoint="notes.create",
        idempotency_key=idempotency_key,
        body=body.model_dump(mode="json"),
    )
    if claimed is not None and claimed.replay is not None:
        return NoteOut.model_validate(claimed.replay)
    n = await svc.create_note(
        ctx.session,
        org_id=ctx.org_id,
        actor_id=ctx.user_id,
        kind=body.kind,
        # ``project_id`` reaches the choke-point as the named
        # ``project_tag_id`` (services/tag_assignment), so its kind is
        # checked there -- a client id passed here is a 400, not a
        # silently mis-filed project.
        project_id=body.project_tag_id,
        title=body.title,
        text=body.text,
        audio_ref=body.audio_ref,
        audio_seconds=body.audio_seconds,
        index_scope=body.index_scope,
    )
    if body.client_tag_id is not None:
        # create_note derives the client from the project, or falls back
        # to the workspace default when there is none (docs/adr/0021).
        # Naming a client is the only way to say which perimeter a
        # projectless note belongs to; a client that contradicts the
        # project is refused here (TAG_CLIENT_PROJECT_MISMATCH) and the
        # whole create rolls back with it.
        await require_tag_kind(
            ctx.session, org_id=ctx.org_id, tag_id=body.client_tag_id, kind=TagKind.client
        )
        await svc.attach_tag(
            ctx.session,
            org_id=ctx.org_id,
            actor_id=ctx.user_id,
            note_id=n.id,
            tag_id=body.client_tag_id,
        )
    # Return the note with its tags: create() enforces a client
    # (default "Personal"), so the response must reflect it.
    tagmap = await svc.tags_by_note(ctx.session, note_ids=[n.id])
    pid = await note_links_svc.primary_task_id_for_note(
        ctx.session, org_id=ctx.org_id, note_id=n.id
    )
    derived = await note_links_svc.derived_task_ids_for_notes(
        ctx.session, org_id=ctx.org_id, note_ids=[n.id]
    )
    titles = await note_links_svc.task_titles_for_ids(
        ctx.session, org_id=ctx.org_id, task_ids=[pid] if pid else []
    )
    out = _out(
        n,
        tagmap.get(n.id, []),
        primary_task_id=pid,
        task_title=titles.get(pid) if pid else None,
        derived_task_ids=derived.get(n.id, []),
        transcript=await svc.get_body(ctx.session, note_id=n.id),
    )
    await idem.store_result(ctx.session, claimed, out.model_dump(mode="json"))
    return out


