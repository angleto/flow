@router.get("", response_model=list[NoteListOut])
async def list_notes(
    ctx: Annotated[TenantCtx, Depends(tenant_ctx, scope="function")],
    include_archived: bool = False,
    include_deleted: bool = False,
    project_id: uuid.UUID | None = None,
    tag_id: uuid.UUID | None = None,
    q: str | None = None,
) -> list[NoteListOut]:
    rows = await svc.list_notes(
        ctx.session,
        org_id=ctx.org_id,
        include_archived=include_archived,
        include_deleted=include_deleted,
        project_id=project_id,
        tag_id=tag_id,
        q=q,
    )
    ids = [n.id for n in rows]
    tagmap = await svc.tags_by_note(ctx.session, note_ids=ids)
    pid_map = await note_links_svc.primary_task_ids_for_notes(
        ctx.session, org_id=ctx.org_id, note_ids=ids
    )
    derived_map = await note_links_svc.derived_task_ids_for_notes(
        ctx.session, org_id=ctx.org_id, note_ids=ids
    )
    count_map = await note_links_svc.linked_task_counts_for_notes(
        ctx.session, org_id=ctx.org_id, note_ids=ids
    )
    title_map = await note_links_svc.task_titles_for_ids(
        ctx.session, org_id=ctx.org_id, task_ids=list(pid_map.values())
    )
    # The list carries a bounded one-line preview, NOT the body: one
    # ``DISTINCT ON`` row per note capped server-side, instead of every
    # part body joined. Loading the bodies here made the response
    # O(total content of the org) -- multiple MB for a screen that
    # renders one line per note. Free-text matching over bodies is
    # ``q``, applied server-side by ``services.notes.list_notes``; the
    # body itself is on ``GET /notes/{id}``.
    previews = await svc._previews_by_note(ctx.session, note_ids=ids)
    return [
        _list_out(
            n,
            tagmap.get(n.id, []),
            primary_task_id=(pid := pid_map.get(n.id)),
            task_title=title_map.get(pid) if pid else None,
            derived_task_ids=derived_map.get(n.id, []),
            linked_task_count=count_map.get(n.id, 0),
            preview=previews.get(n.id),
        )
        for n in rows
    ]


@router.get("/{note_id}", response_model=NoteOut)
async def get_note(
    note_id: uuid.UUID,
    ctx: Annotated[TenantCtx, Depends(tenant_ctx, scope="function")],
) -> NoteOut:
    n = await svc.get_note(ctx.session, org_id=ctx.org_id, note_id=note_id)
    tagmap = await svc.tags_by_note(ctx.session, note_ids=[n.id])
    pid = await note_links_svc.primary_task_id_for_note(
        ctx.session, org_id=ctx.org_id, note_id=n.id
    )
    derived = await note_links_svc.derived_task_ids_for_notes(
        ctx.session, org_id=ctx.org_id, note_ids=[n.id]
    )
    counts = await note_links_svc.linked_task_counts_for_notes(
        ctx.session, org_id=ctx.org_id, note_ids=[n.id]
    )
    titles = await note_links_svc.task_titles_for_ids(
        ctx.session, org_id=ctx.org_id, task_ids=[pid] if pid else []
    )
    # Phase 2a: GET /notes/{id} includes the ordered parts plus the
    # caller's per-part collapse state. List endpoints leave parts
    # empty for payload economy; the single-note path is the canonical
    # surface for the SPA editor that needs every block.
    parts_rows = await parts_svc.list_parts(ctx.session, org_id=ctx.org_id, note_id=n.id)
    ui = await parts_svc.get_ui_states_for_user(ctx.session, user_id=ctx.user_id, note_id=n.id)
    parts = [_part_out(p, ui_collapsed=ui.get(p.id, False)) for p in parts_rows]
    return _out(
        n,
        tagmap.get(n.id, []),
        primary_task_id=pid,
        task_title=titles.get(pid) if pid else None,
        derived_task_ids=derived.get(n.id, []),
        linked_task_count=counts.get(n.id, 0),
        parts=parts,
    )


